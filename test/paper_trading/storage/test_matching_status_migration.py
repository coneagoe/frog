def test_postgresql_converts_labels_and_verifies_active_partial_index(postgres_schema):
    engine, schema = postgres_schema
    with _connection(engine, schema) as connection:
        for status in LABELS:
            connection.execute(
                text("INSERT INTO paper_matching_runs (trade_date, scope_key, status) VALUES (:date, :scope, :status)"),
                {"date": date(2026, 7, 31), "scope": status, "status": status},
            )
        result = migrate_paper_matching_status_enum(connection)

        assert result.converted is True
        assert result.labels == LABELS
        assert result.index_verified is True
        assert (
            connection.execute(
                text(
                    "SELECT t.typname FROM pg_type t "
                    "JOIN pg_namespace n ON n.oid = t.typnamespace "
                    "WHERE n.nspname = :schema AND t.typname = 'paper_matching_run_status'"
                ),
                {"schema": schema},
            ).scalar_one()
            == "paper_matching_run_status"
        )
        assert connection.execute(
            text(
                "SELECT enumlabel FROM pg_enum "
                "JOIN pg_type ON pg_type.oid = pg_enum.enumtypid "
                "JOIN pg_namespace ON pg_namespace.oid = pg_type.typnamespace "
                "WHERE pg_namespace.nspname = :schema "
                "AND pg_type.typname = 'paper_matching_run_status' ORDER BY enumsortorder"
            ),
            {"schema": schema},
        ).all() == [(label,) for label in LABELS]
        assert (
            connection.execute(
                text(
                    "SELECT pg_get_expr(indpred, indrelid) FROM pg_index "
                    "JOIN pg_class ON pg_class.oid = pg_index.indexrelid "
                    "JOIN pg_namespace ON pg_namespace.oid = pg_class.relnamespace "
                    "WHERE pg_namespace.nspname = :schema "
                    "AND pg_class.relname = 'uq_matching_active_scope'"
                ),
                {"schema": schema},
            )
            .scalar_one()
            .lower()
            .find("running")
            >= 0
        )
        assert (
            connection.execute(
                text(
                    "SELECT pg_get_expr(indpred, indrelid) FROM pg_index "
                    "JOIN pg_class ON pg_class.oid = pg_index.indexrelid "
                    "JOIN pg_namespace ON pg_namespace.oid = pg_class.relnamespace "
                    "WHERE pg_namespace.nspname = :schema "
                    "AND pg_class.relname = 'uq_matching_active_scope'"
                ),
                {"schema": schema},
            )
            .scalar_one()
            .lower()
            .find("paper_matching_run_status")
            >= 0
        )


