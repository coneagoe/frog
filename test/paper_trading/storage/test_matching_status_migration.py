def test_postgresql_enum_rejects_invalid_insert_and_enforces_active_index(postgres_schema):
    engine, schema = postgres_schema
    with _connection(engine, schema) as connection:
        migrate_paper_matching_status_enum(connection)
        savepoint = connection.begin_nested()
        try:
            with pytest.raises(Exception):
                connection.execute(
                    text(
                        "INSERT INTO paper_matching_runs (trade_date, scope_key, status) "
                        "VALUES ('2026-07-31', 'bad', 'invalid')"
                    )
                )
        finally:
            savepoint.rollback()
        connection.execute(
            text(
                "INSERT INTO paper_matching_runs (trade_date, scope_key, status) "
                "VALUES ('2026-07-31', 'all', 'running')"
            )
        )
        savepoint = connection.begin_nested()
        try:
            with pytest.raises(Exception):
                connection.execute(
                    text(
                        "INSERT INTO paper_matching_runs (trade_date, scope_key, status) "
                        "VALUES ('2026-07-31', 'all', 'running')"
                    )
                )
        finally:
            savepoint.rollback()
